'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const app=path.resolve(__dirname,'../app');
const context={window:{},I18n:{value:x=>x,ui:(x,y)=>y,locale:()=> 'nl-NL'},Intl,Date,JSON};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(app,'schrijfsjablonen.js'),'utf8'),context);
const templates=context.window.Schrijfsjablonen;
const business={name:'A_B [zorg] & Partners',address:'Voorbeeldstraat 1\n1000 AA Plaats',email:'info@example.test',logo:'data:image/png;base64,QUJD'};
const brief=templates.brief(business,new Date('2026-11-02T12:00:00Z'),'Afspraak [bevestigd] & vervolg');
assert(brief.includes('title: "Afspraak [bevestigd] & vervolg"'));
assert(brief.includes('type: brief'));
assert(brief.includes('A\\_B \\[zorg\\] &amp; Partners'));
assert(brief.includes('![Briefhoofd](data:image/png;base64,QUJD)'));
assert(brief.includes('Voorbeeldstraat 1  \n1000 AA Plaats'));
assert(brief.includes('2 november 2026'));
business.name='Nieuwe organisatie';business.logo='';assert(!brief.includes('Nieuwe organisatie'));assert(brief.includes('![Briefhoofd]'));
assert(!templates.brief(business).includes('![Briefhoofd]'));
assert(!templates.brief({...business,logo:'javascript:alert(1)'}).includes('javascript:'));
assert.throws(()=>templates.brief({name:''}),/bedrijfsnaam/);
assert(templates.artikel('Artikel').startsWith('# Artikel'));
assert(templates.nieuwsbrief('Nieuwsbrief').startsWith('# Nieuwsbrief'));
console.log('PASS: portable letterhead/logo snapshot, exact title metadata, escaped organisation punctuation, address/date, no-logo and invalid-logo handling, existing templates preserved.');
